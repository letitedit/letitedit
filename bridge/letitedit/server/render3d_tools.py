"""MCP tool letitedit_3d: list a 3D model's parts, preview and render generated 3D clips (render3d.py).

    run(action, ...)   same as the tool, without MCP
    job(ctx)           the 'render3d_tools:job' job kind (a render as a background job)
"""
from __future__ import annotations

import json
from pathlib import Path

import letitedit.pictures.render3d as render3d

JOB_KIND = 'render3d_tools:job'
JOB_OVER_S = 60.0       # job=None: estimated renders above this many seconds run as a background job

