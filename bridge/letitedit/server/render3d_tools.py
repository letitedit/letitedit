SPEC_KEYS = ('model', 'text', 'font', 'font_path', 'front_color', 'side_color', 'scene', 'duration', 'easing', 'move', 'highlight', 'xray', 'hide', 'callouts', 'lighting',
             'light_strength', 'world_color', 'background', 'ground', 'engine', 'samples', 'view_transform',
             'format', 'crf', 'frame_ignore')


def _project_profile(project):
    import letitedit.timeline.edit_script as es
    prof = es.read(project)['profile']
    return [int(prof['width']), int(prof['height'])], float(prof['fps']), Path(project).parent / 'made'


def build_spec(spec=None, **kw):
    s = dict(spec or {})
    s.update({k: v for k, v in kw.items() if k in SPEC_KEYS and v is not None})
    return s


def job(ctx):
    inp = ctx.inputs
    r = render3d.render(inp['spec'], inp['size'][0], inp['size'][1], inp['fps'], out_dir=inp.get('out_dir'),
                        out=inp.get('out'), progress=lambda f, m=None: ctx.progress(min(0.95, f), m))
    return {'file': r['path'], 'sheet': r.get('sheet'), 'missing': r.get('missing'), 'item': {'render3d': r['spec']}}


def run(action='preview', spec=None, size=None, fps=None, project=None, out=None, count=6, times=None, job=None,
        refresh=False, **kw):
    s = build_spec(spec, **kw)
    if action == 'list':
        if not s.get('model'):
            raise ValueError('list needs a model')
        info = render3d.inspect(s['model'], s.get('scene'), refresh=refresh)
        return {'text': render3d.inspect_text(info), 'info': info}
    norm = render3d.normalise(s)
    if action == 'preview':
        w, h = size or [640, 360]
        r = render3d.preview(norm, w, h, fps or 30.0, count=count, times=times, out=out)
        text = (f"preview of {render3d.describe(norm)}: {len(r['frames'])} frames at {w}x{h}, {r['seconds']} s, "
                f"engine {r['engine']}"
                + (f"\ntargets not found: {r['missing']}" if r.get('missing') else '')
                + '\ncamera keys: ' + json.dumps([{k: (round(v, 3) if isinstance(v, float) else
                                                       [round(x, 3) for x in v] if isinstance(v, list) else v)
                                                   for k, v in key.items()} for key in r['keys']])
                + f"\nsubject bounds {[[round(v, 3) for v in b] for b in r['bounds']]}, radius {r['radius']:.3f}"
                + f"\nsheet: {r['sheet']}")
        return {'text': text, 'sheet': r['sheet'], 'result': {k: v for k, v in r.items() if k != 'spec'}}
    if action != 'render':
        raise ValueError("action must be 'list', 'preview' or 'render'")
    out_dir = None
    if project:
        size, fps, out_dir = _project_profile(project)
    w, h = size or [1920, 1080]
    fps = float(fps or 30.0)
    est = render3d.estimate_s(norm, w, h, fps)
    if job or (job is None and est > JOB_OVER_S):
        import letitedit.core.jobs as jobs
        st = jobs.submit(JOB_KIND, {'spec': norm, 'size': [w, h], 'fps': fps,
                                    'out_dir': str(out_dir) if out_dir else None, 'out': out},
                         label=f"3D render {Path(norm['model']).name}")
        return {'text': f"job {st.get('id') or st.get('job_id')} queued: {render3d.describe(norm)}, {w}x{h} "
                        f"{fps:g} fps, {norm['duration']} s (estimate {est:.0f} s; letitedit_jobs to follow it)",
                'job': st, 'estimate_s': round(est), 'item': {'render3d': norm}}
    r = render3d.render(norm, w, h, fps, out_dir=out_dir, out=out)
    text = (f"{'cached' if r['cached'] else 'rendered'} {r['path']} ({r['format']}, {w}x{h}, {fps:g} fps, "
            f"{norm['duration']} s, {r.get('seconds')} s, engine {r.get('engine')})"
            + (f"\ntargets not found: {r['missing']}" if r.get('missing') else '')
            + f"\nsidecar: {r['sidecar']}\nsheet: {r.get('sheet')}"
            + "\ntimeline item (letitedit_timeline_apply): {render3d: <spec in the result>}")
    return {'text': text, 'sheet': r.get('sheet'), 'file': r['path'], 'item': {'render3d': norm},
            'result': {k: v for k, v in r.items() if k != 'spec'}}


def register(mcp, Image):
    def letitedit_3d(action: str = 'preview', model: str | None = None, text: str | None = None,
                   font: str | None = None, front_color: str | None = None, side_color: str | None = None,
                   move: str | dict | None = None,
                   duration: float | None = None, highlight: str | list | dict | None = None,
                   xray: str | list | dict | None = None, hide: str | list | None = None,
                   callouts: list | dict | None = None, lighting: str | None = None, background: str | None = None,
                   ground: str | None = None, engine: str | None = None, samples: int | None = None,
                   format: str | None = None, spec: dict | None = None, size: list[int] | None = None,
                   fps: float | None = None, project: str | None = None, out: str | None = None, count: int = 6,
                   times: list[float] | None = None, job: bool | None = None, refresh: bool = False) -> list:
        try:
            rep = run(action, spec=spec, size=size, fps=fps, project=project, out=out, count=count, times=times,
                      job=job, refresh=refresh, model=model, text=text, font=font,
                      front_color=front_color, side_color=side_color, move=move, duration=duration, highlight=highlight,
                      xray=xray, hide=hide, callouts=callouts, lighting=lighting, background=background,
                      ground=ground, engine=engine, samples=samples, format=format)
        except (FileNotFoundError, ValueError, KeyError, RuntimeError, TimeoutError) as e:
            return [{'error': f'{type(e).__name__}: {e}'}]
        outl = []
        if rep.get('sheet') and Path(rep['sheet']).exists():
            outl.append(Image(data=Path(rep['sheet']).read_bytes(), format='jpeg'))
        outl.append(rep['text'])
        outl.append({k: v for k, v in rep.items() if k != 'text'})
        return outl
    letitedit_3d.__doc__ = DOC
    mcp.tool(structured_output=False)(letitedit_3d)
