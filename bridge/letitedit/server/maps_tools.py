"""MCP tool letitedit_map: generated maps from clips' GPS with offline map data (maps.py).

    run(action, ...)   same as the tool, without MCP
    job(ctx)           the 'maps_tools:job' job kind (a map render as a background job)
"""
from __future__ import annotations

import json
from pathlib import Path

import letitedit.pictures.maps as maps

JOB_KIND = 'maps_tools:job'
JOB_OVER_S = 60.0


