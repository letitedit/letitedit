SPEC_KEYS = tuple(maps.DEFAULTS)


def _project_profile(project):
    import letitedit.timeline.edit_script as es
    prof = es.read(project)['profile']
    return [int(prof['width']), int(prof['height'])], float(prof['fps']), Path(project).parent / 'made'


def build_spec(spec=None, **kw):
    s = dict(spec or {})
    s.update({k: v for k, v in kw.items() if k in SPEC_KEYS and v is not None})
    return s


def job(ctx):
    inp = ctx.inputs
    r = maps.render(inp['spec'], inp['size'][0], inp['size'][1], inp['fps'], out_dir=inp.get('out_dir'),
                    out=inp.get('out'), progress=lambda f, m=None: ctx.progress(min(0.95, f), m))
    return {'file': r['path'], 'sheet': r.get('sheet'), 'attribution': r.get('attribution'),
            'item': {'map': r.get('spec', inp['spec'])}}


def _stops_text(stops_, notes):
    lines = [f'{len(stops_)} stops:']
    for i, s in enumerate(stops_):
        lines.append(f"  {i} {s['label']} ({s.get('place', '')}{', %.1f km from it' % s['km_from_place'] if s.get('km_from_place') is not None else ''}) "
                     f"{s['lat']:.4f}, {s['lon']:.4f} recorded {s.get('recorded')} clips {len(s.get('clips') or [])}")
    if notes:
        lines.append('notes: ' + '; '.join(notes[:20]) + (f' (+{len(notes) - 20})' if len(notes) > 20 else ''))
    return '\n'.join(lines)


def run(action='preview', spec=None, size=None, fps=None, project=None, out=None, count=6, times=None, job=None,
        **kw):
    s = build_spec(spec, **kw)
    if action == 'stops':
        st, notes = maps.stops(s.get('clips'), s.get('points'), s.get('order', 'recorded'), s.get('merge_km', 1.0))
        return {'text': _stops_text(st, notes), 'stops': st, 'notes': notes}
    if action == 'still':
        s['still'] = True
        action = 'render'
    norm = maps.normalise(s)
    if action == 'preview':
        w, h = size or [640, 360]
        r = maps.preview(norm, w, h, fps or 30.0, count=count, times=times, out=out)
        text = (f"map preview: {len(r['times'])} frames at {w}x{h}, {r['seconds']} s; km across "
                f"{r['km_across']}; attribution: {r['attribution'] or 'none'}\n" + _stops_text(r['stops'], r['notes'])
                + f"\nsheet: {r['sheet']}")
        return {'text': text, 'sheet': r['sheet'], 'result': {k: v for k, v in r.items() if k != 'spec'}}
    if action != 'render':
        raise ValueError("action must be 'stops', 'preview', 'render' or 'still'")
    out_dir = None
    if project:
        size, fps, out_dir = _project_profile(project)
    w, h = size or [1920, 1080]
    fps = float(fps or 30.0)
    est = maps.estimate_s(norm, w, h, fps)
    item = {'map': maps.recipe({'map': norm})['spec']}
    if job or (job is None and est > JOB_OVER_S):
        import letitedit.core.jobs as jobs
        st = jobs.submit(JOB_KIND, {'spec': norm, 'size': [w, h], 'fps': fps,
                                    'out_dir': str(out_dir) if out_dir else None, 'out': out}, label='map render')
        return {'text': f"job {st.get('id') or st.get('job_id')} queued: map {w}x{h} {fps:g} fps "
                        f"{norm['duration']} s (estimate {est:.0f} s; letitedit_jobs to follow it)",
                'job': st, 'estimate_s': round(est), 'item': item}
    r = maps.render(norm, w, h, fps, out_dir=out_dir, out=out)
    text = (f"{'cached' if r['cached'] else 'rendered'} {r['path']} ({r['format']}, {w}x{h}"
            + ('' if norm['still'] else f", {fps:g} fps, {norm['duration']} s") + f", {r.get('seconds')} s)\n"
            + f"attribution: {r.get('attribution') or 'none'}\n" + _stops_text(r['stops'] or [], r.get('notes') or [])
            + f"\nsidecar: {r['sidecar']}" + (f"\nsheet: {r['sheet']}" if r.get('sheet') else '')
            + ('' if norm['still'] else "\ntimeline item (letitedit_timeline_apply): {map: <spec in the result>}"))
    return {'text': text, 'sheet': r.get('sheet') or (r['path'] if norm['still'] else None), 'file': r['path'],
            'item': None if norm['still'] else item, 'result': r}


def register(mcp, Image):
    def letitedit_map(action: str = 'preview', clips: str | list[str] | None = None, points: list | None = None,
                    style: str | None = None, camera: str | None = None, duration: float | None = None,
                    title: str | None = None, spec: dict | None = None, size: list[int] | None = None,
                    fps: float | None = None, project: str | None = None, out: str | None = None, count: int = 6,
                    times: list[float] | None = None, job: bool | None = None) -> list:
        try:
            rep = run(action, spec=spec, size=size, fps=fps, project=project, out=out, count=count, times=times,
                      job=job, clips=clips, points=points, style=style, camera=camera, duration=duration,
                      title=title)
        except (FileNotFoundError, ValueError, KeyError, RuntimeError) as e:
            return [{'error': f'{type(e).__name__}: {e}'}]
        outl = []
        sh = rep.get('sheet')
        if sh and Path(sh).exists():
            fmt = 'png' if str(sh).lower().endswith('.png') else 'jpeg'
            outl.append(Image(data=Path(sh).read_bytes(), format=fmt))
        outl.append(rep['text'])
        outl.append(json.loads(json.dumps({k: v for k, v in rep.items() if k != 'text'}, default=str)))
        return outl
    letitedit_map.__doc__ = DOC
    mcp.tool(structured_output=False)(letitedit_map)
