def ffmpeg():
    import letitedit.timeline.made as made
    return str(made.ffmpeg_exe())


def rgba(c, default=(255, 255, 255, 255)):
    """'#rrggbb' | '#rrggbbaa' | [r, g, b(, a)] (0-255) | None -> (r, g, b, a)."""
    if c is None:
        return default
    if isinstance(c, (list, tuple)):
        v = [int(round(float(x))) for x in c]
        return tuple(v + [255] * (4 - len(v)))[:4]
    s = str(c).strip().lstrip('#')
    if s.lower() in ('none', 'transparent', ''):
        return (0, 0, 0, 0)
    if len(s) == 3:
        s = ''.join(ch * 2 for ch in s)
    if len(s) not in (6, 8):
        raise ValueError(f'colour {c!r}: use #rrggbb or #rrggbbaa')
    v = [int(s[i:i + 2], 16) for i in range(0, len(s), 2)]
    return tuple(v + [255] * (4 - len(v)))


def font(name='Inter', size=32, weight=600):
    from PIL import ImageFont
    try:
        import letitedit.catalogs.fonts as fonts
        return fonts.pil_font(name, max(4, int(size)), weight=int(weight))
    except Exception:  # noqa: BLE001
        for f in ('C:/Windows/Fonts/segoeuib.ttf', 'C:/Windows/Fonts/arialbd.ttf'):
            if Path(f).exists():
                return ImageFont.truetype(f, max(4, int(size)))
        return ImageFont.load_default()


def background(width, height, spec):
    """An RGBA PIL image for a background spec: 'transparent' | '#rrggbb(aa)' | 'gradient:#top,#bottom'."""
    from PIL import Image
    import numpy as np
    spec = spec or 'transparent'
    if isinstance(spec, str) and spec.startswith('gradient:'):
        a, b = (rgba(x) for x in spec.split(':', 1)[1].split(','))
        t = np.linspace(0, 1, height)[:, None, None]
        arr = (np.array(a)[None, None, :] * (1 - t) + np.array(b)[None, None, :] * t)
        arr = np.repeat(arr, width, axis=1).astype('uint8')
        return Image.fromarray(arr, 'RGBA')
    if spec == 'transparent':
        return Image.new('RGBA', (width, height), (0, 0, 0, 0))
    return Image.new('RGBA', (width, height), rgba(spec))


def meta_args(kind, title, comment):
    return ['-metadata', f'title=Generated {kind}: {title}'[:250],
            '-metadata', f'comment=generated by letitedit - not camera footage; {comment}'[:1000],
            '-metadata', 'letitedit_ai_generated=1']


class Encoder:
    """Feed RGBA frames (PIL images or HxWx4 uint8 arrays); writes mp4 / mov (ProRes 4444) / png folder."""

    def __init__(self, path, width, height, fps, fmt='mp4', crf=16, preset='medium', kind='clip', title='',
                 comment='', matte='#000000'):
        self.path = Path(path)
        self.fmt = fmt
        self.n = 0
        self.matte = rgba(matte)
        self.size = (int(width), int(height))
        self.proc = None
        if fmt == 'png':
            self.path.mkdir(parents=True, exist_ok=True)
            return
        if fmt == 'mp4':
            codec = ['-c:v', 'libx264', '-crf', str(crf), '-preset', preset, '-pix_fmt', 'yuv420p',
                     '-movflags', '+faststart']
        elif fmt == 'mov':
            codec = ['-c:v', 'prores_ks', '-profile:v', '4444', '-pix_fmt', 'yuva444p10le', '-vendor', 'apl0']
        else:
            raise ValueError(f'format must be one of {FORMATS}')
        cmd = [ffmpeg(), '-hide_banner', '-loglevel', 'error', '-y', '-f', 'rawvideo', '-pix_fmt', 'rgba',
               '-s', f'{width}x{height}', '-r', f'{float(fps):.6f}', '-i', '-', '-an', *codec,
               *meta_args(kind, title, comment), str(self.path)]
        self.proc = subprocess.Popen(cmd, stdin=subprocess.PIPE, stderr=subprocess.PIPE, creationflags=NO_WINDOW)

    def add(self, frame):
        from PIL import Image
        import numpy as np
        im = frame if isinstance(frame, Image.Image) else Image.fromarray(frame, 'RGBA')
        if im.size != self.size:
            im = im.resize(self.size, Image.LANCZOS)
        if im.mode != 'RGBA':
            im = im.convert('RGBA')
        if self.fmt == 'png':
            im.save(self.path / f'frame_{self.n:05d}.png', compress_level=3)
        else:
            if self.fmt == 'mp4':
                base = Image.new('RGBA', im.size, self.matte[:3] + (255,))
                base.alpha_composite(im)
                im = base
            self.proc.stdin.write(np.asarray(im, dtype='uint8').tobytes())
        self.n += 1

    def close(self):
        if self.proc is None:
            return
        self.proc.stdin.close()
        err = self.proc.stderr.read().decode('utf-8', 'replace')
        self.proc.stderr.close()
        code = self.proc.wait()
        if code != 0:
            raise RuntimeError(f'ffmpeg encode failed: {err[-1500:]}')

    def abort(self):
        if self.proc is not None:
            try:
                self.proc.kill()
            except OSError:
                pass


def sidecar(path, data):
    p = Path(str(path) + '.json') if not Path(path).is_dir() else Path(path) / 'generated.json'
    p.write_text(json.dumps(dict(data, generated=True), indent=1, default=str), encoding='utf-8')
    return str(p)


def sheet(images, labels, out, cols=3, tile_w=480, checker=True):
    """A JPEG frame sheet of RGBA images (transparent parts on a checkerboard) with a label on each."""
    from PIL import Image, ImageDraw
    tiles = []
    for im, lab in zip(images, labels):
        im = im if isinstance(im, Image.Image) else Image.open(im)
        im = im.convert('RGBA')
        th = max(1, round(im.height * tile_w / im.width))
        im = im.resize((tile_w, th), Image.LANCZOS)
        bg = Image.new('RGBA', im.size, (60, 60, 60, 255))
        if checker:
            d = ImageDraw.Draw(bg)
            s = 12
            for y in range(0, th, s):
                for x in range(0, tile_w, s):
                    if (x // s + y // s) % 2:
                        d.rectangle((x, y, x + s - 1, y + s - 1), fill=(90, 90, 90, 255))
        bg.alpha_composite(im)
        d = ImageDraw.Draw(bg)
        d.rectangle((0, 0, 8 * len(lab) + 8, 16), fill=(0, 0, 0, 255))
        d.text((4, 2), lab, fill=(255, 230, 0, 255))
        tiles.append(bg.convert('RGB'))
    if not tiles:
        raise ValueError('no frames for the sheet')
    cols = max(1, min(cols, len(tiles)))
    th = max(t.height for t in tiles)
    rows = (len(tiles) + cols - 1) // cols
    out_im = Image.new('RGB', (cols * tile_w, rows * th), (28, 28, 28))
    for i, t in enumerate(tiles):
        out_im.paste(t, ((i % cols) * tile_w, (i // cols) * th))
    Path(out).parent.mkdir(parents=True, exist_ok=True)
    out_im.save(out, quality=88)
    return str(out)


def even_frames(total, count):
    """`count` frame indices spread over 0..total-1 (first and last included)."""
    total, count = int(total), max(1, int(count))
    if total <= 1 or count == 1:
        return [0] if count == 1 or total <= 1 else [0]
    if count >= total:
        return list(range(total))
    return sorted({round(i * (total - 1) / (count - 1)) for i in range(count)})
