// Builds written-music.mjs, the one file customers get, from cli.ts and engine\ with the esbuild already in motion\engine.
//   node written-music\build.mjs [path to esbuild's package folder]
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { existsSync, readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const dir = [process.argv[2], join(here, "../motion/engine/node_modules/esbuild"), "C:/LetItEdit/motion/engine/node_modules/esbuild"].find((p) => p && existsSync(p));
if (!dir) throw new Error("no esbuild: run npm ci in motion\\engine, or name its folder");
const { buildSync } = createRequire(import.meta.url)(dir);
const banner = `// letitedit's music writer: music written as a score, performed and mixed in code. Generated by build.mjs; edit cli.ts and engine\\.
// Based on anidoodle by Alex Greenshpun, Copyright 2026 Alex Greenshpun, Apache-2.0 (https://github.com/alexgreensh/anidoodle,
// commit 6ae8827); changed by letitedit, 4 Nov 2026. See LICENSE-anidoodle.txt and NOTICE-anidoodle.txt beside this file.`;
const r = buildSync({ entryPoints: [join(here, "cli.ts")], outfile: join(here, "written-music.mjs"), bundle: true, format: "esm", platform: "node", target: "node22",
  logLevel: "error", banner: { js: banner }, legalComments: "none", metafile: true, charset: "utf8" });
const inputs = Object.keys(r.metafile.inputs), out = join(here, "written-music.mjs");
for (const bad of ["child_process", "soundfetch", "remotion", "esbuild"]) if (readFileSync(out, "utf8").replace(banner, "").includes(bad)) console.log(`NOTE: the bundle mentions "${bad}"`);
console.log(`written-music.mjs: ${(readFileSync(out).length / 1024).toFixed(0)} KB from ${inputs.length} files`);
